"""Write ``requirements-api.txt`` pinned to the versions installed here, so the Docker image loads the saved model exactly as it was trained."""
from __future__ import annotations

import argparse
import json
import logging
import sys
from importlib import metadata
from pathlib import Path
from typing import List, Optional, Sequence

from fraud.logging_utils import configure_logging

LOGGER = logging.getLogger(__name__)
BASE_PACKAGES = ("numpy", "pandas", "scipy", "scikit-learn", "joblib", "pydantic", "fastapi", "uvicorn")


def packages_for(model_variant: str) -> List[str]:
    """The packages the service needs for a model such as ``lightgbm/smote``: the base set, plus the model's own library (shap for forests)."""
    name = model_variant.split("/")[0]
    extra = {"lightgbm": ["lightgbm"], "xgboost": ["xgboost"], "random_forest": ["shap"]}.get(name, [])
    return [*BASE_PACKAGES, *extra]


def pinned(packages: Sequence[str]) -> List[str]:
    """``name==version`` for each package.

    Raises:
        RuntimeError: Listing every package that is not installed.
    """
    lines, missing = [], []
    for package in packages:
        try:
            lines.append(f"{package}=={metadata.version(package)}")
        except metadata.PackageNotFoundError:
            missing.append(package)
    if missing:
        raise RuntimeError(f"not installed: {', '.join(missing)} (pip install {' '.join(missing)})")
    return lines


def main(argv: Optional[Sequence[str]] = None) -> int:
    """Command-line entry point."""
    parser = argparse.ArgumentParser(description="Pin the API image's requirements to the installed versions (Step 9).")
    parser.add_argument("--root", type=Path, default=Path("."))
    parser.add_argument("--log-level", default="INFO")
    args = parser.parse_args(argv)
    configure_logging(args.log_level)
    meta_path = args.root / "models" / "supervised_best.json"
    if not meta_path.is_file():
        raise SystemExit(f"{meta_path} not found: run Step 5 first")
    variant = json.loads(meta_path.read_text(encoding="utf-8"))["model_variant"]
    lines = pinned(packages_for(variant))
    (args.root / "requirements-api.txt").write_text("# generated by python -m fraud.pin_requirements\n" + "\n".join(lines) + "\n", encoding="utf-8")
    LOGGER.info("wrote requirements-api.txt for %s (%d packages); build with --build-arg PYTHON_VERSION=%d.%d", variant, len(lines), *sys.version_info[:2])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
